-- Research staging only. No changes to existing source, account or model tables.
CREATE TABLE tinix_dataset_records (
  internal_id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  source_name VARCHAR(32) NOT NULL DEFAULT 'TINIX_AI',
  dataset_name VARCHAR(160) NOT NULL,
  dataset_revision CHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  dataset_license VARCHAR(64) NOT NULL,
  row_reference VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  imported_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  raw_payload JSON NOT NULL,
  raw_numeric_ieee754 JSON NOT NULL,
  payload_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  name LONGTEXT NULL,
  description LONGTEXT NULL,
  property_type_name TEXT NULL,
  province_name TEXT NULL,
  district_name TEXT NULL,
  ward_name TEXT NULL,
  street_name TEXT NULL,
  project_name TEXT NULL,
  price LONGTEXT NULL,
  area DOUBLE NULL,
  floor_count DOUBLE NULL,
  frontage_width DOUBLE NULL,
  house_depth DOUBLE NULL,
  road_width DOUBLE NULL,
  bedroom_count DOUBLE NULL,
  bathroom_count DOUBLE NULL,
  house_direction TEXT NULL,
  balcony_direction TEXT NULL,
  published_at TEXT NULL,
  price_vnd DECIMAL(24,2) NULL,
  area_sqm DECIMAL(18,6) NULL,
  normalized_type VARCHAR(32) NULL,
  district VARCHAR(100) NULL,
  ward VARCHAR(100) NULL,
  transaction_type VARCHAR(16) NOT NULL DEFAULT 'UNKNOWN',
  transaction_basis VARCHAR(64) NOT NULL DEFAULT 'NOT_ESTABLISHED',
  quality_status VARCHAR(40) NOT NULL,
  quality_issues JSON NOT NULL,
  verification_status VARCHAR(16) NOT NULL DEFAULT 'UNVERIFIED',
  research_only BOOLEAN NOT NULL DEFAULT TRUE,
  listing_availability VARCHAR(16) NOT NULL DEFAULT 'UNKNOWN',
  is_protected_holdout BOOLEAN NOT NULL DEFAULT FALSE,
  duplicate_group CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  is_duplicate_representative BOOLEAN NOT NULL DEFAULT FALSE,
  quality_rule_version VARCHAR(40) NOT NULL,
  PRIMARY KEY (internal_id),
  UNIQUE KEY uq_tinix_row (dataset_revision,row_reference),
  KEY ix_tinix_hybrid (quality_status,is_duplicate_representative,is_protected_holdout,transaction_type,price_vnd),
  KEY ix_tinix_group (duplicate_group),
  CONSTRAINT ck_tinix_research CHECK (source_name='TINIX_AI' AND research_only=TRUE AND verification_status='UNVERIFIED' AND listing_availability='UNKNOWN'),
  CONSTRAINT ck_tinix_quality CHECK (quality_status IN ('HYBRID_ELIGIBLE_RESEARCH','NEEDS_REVIEW','EXCLUDED')),
  CONSTRAINT ck_tinix_transaction CHECK (transaction_type IN ('SALE','RENT','UNKNOWN')),
  CONSTRAINT ck_tinix_price CHECK (price_vnd IS NULL OR price_vnd>0),
  CONSTRAINT ck_tinix_area CHECK (area_sqm IS NULL OR area_sqm>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
